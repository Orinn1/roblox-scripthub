/**
 * คำนวณ Hash ประจำวันตาม UserId, หมวดหมู่ และ วันที่
 */
function getDailySeed(userId, topic, dateStr) {
    const raw = `${userId || 'guest'}-${topic}-${dateStr}`;
    let hash = 0;
    for (let i = 0; i < raw.length; i++) {
        hash = ((hash << 5) - hash) + raw.charCodeAt(i);
        hash |= 0;
    }
    return Math.abs(hash);
}

/**
 * สุ่มหรือคำนวณเปิดไพ่ทาโรต์ตามหมวดหมู่และ User ID
 */
function drawTarotCard(topic = 'overall', username = 'คุณ', userId = null) {
    const config = TOPIC_CONFIG[topic] || TOPIC_CONFIG.overall;

    const now = new Date();
    // วันที่ในไทม์โซนประเทศไทย
    const dateStr = now.toLocaleDateString('en-CA', { timeZone: 'Asia/Bangkok' }); // YYYY-MM-DD
    const thaiDateText = now.toLocaleDateString('th-TH', {
        timeZone: 'Asia/Bangkok',
        day: 'numeric',
        month: 'long',
        year: 'numeric'
    });

    let cardIndex = 0;
    let isReversed = false;
    let timeIndex = 0;
    let lucky2 = 0;
    let lucky3 = 0;

    if (userId) {
        // Deterministic daily reading (ล็อกดวงตาม User ID และวันที่)
        const seed = getDailySeed(userId, topic, dateStr);
        cardIndex = seed % TAROT_CARDS.length;
        // โอกาส 25% ที่จะได้ไพ่กลับหัว เพื่อความสมจริงในศาสตร์ทาโรต์
        isReversed = ((seed >> 2) % 4 === 0);
        timeIndex = (seed >> 4) % AUSPICIOUS_TIMES.length;
        const card = TAROT_CARDS[cardIndex];
        const base = card.luckyBase || [1, 5, 9];
        lucky2 = ((base[0] * 10 + (seed % 10)) % 90) + 10;
        lucky3 = ((base[1] * 100 + (seed % 100)) % 900) + 100;
    } else {
        // สุ่มปกติหากไม่มี User ID
        cardIndex = Math.floor(Math.random() * TAROT_CARDS.length);
        isReversed = Math.random() < 0.25;
        timeIndex = Math.floor(Math.random() * AUSPICIOUS_TIMES.length);
        lucky2 = Math.floor(10 + Math.random() * 90);
        lucky3 = Math.floor(100 + Math.random() * 900);
    }

    const card = TAROT_CARDS[cardIndex];
    const reading = isReversed ? card.reversed : card.upright;

    return {
        topicTitle: config.title,
        fieldTitle: config.fieldTitle,
        cardName: card.name,
        cardEnglish: card.english,
        positionText: isReversed ? '*(ไพ่กลับหัว 🔄 — มีคำเตือน)*' : '*(ไพ่หัวตั้ง ⬆️)*',
        isReversed,
        cardImage: card.image,
        colorHex: isReversed ? '#D35400' : card.color,
        stars: reading.stars,
        prediction: reading[config.propName] || reading.overall,
        warning: reading.warning,
        advice: reading.advice,
        luckyNumbers: `${lucky2}, ${lucky3}`,
        auspiciousColor: card.colorName,
        inauspiciousColor: card.inauspiciousColor,
        auspiciousTime: AUSPICIOUS_TIMES[timeIndex],
        elementPlanet: `${card.element} • ${card.planet}`,
        dateText: thaiDateText
    };
}

